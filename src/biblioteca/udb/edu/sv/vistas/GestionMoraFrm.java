    private void tbl_mis_morasMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tbl_mis_morasMouseClicked
        if(RoleManager.tienePermiso("GESTION_MORAS","MODIFICAR")){
            int index = tbl_mis_moras.getSelectedRow();
            TableModel modeloConfig = tbl_mis_moras.getModel();
            int idMora = Integer.parseInt(modeloConfig.getValueAt(index, 0).toString());
            BigDecimal monto = new BigDecimal(modeloConfig.getValueAt(index, 6).toString());
            
            Usuario user = new Usuario();
            user.setIdUsuario(sesion.getIdUsuario());
            user.setNombre(sesion.getNombre());
            Rol rol = new Rol();
            rol.setNombreRol(sesion.getRol());
            user.setRol(rol);
            
            if (JOptionPane.showConfirmDialog(null, "Esta seguro de confirmar pago de mora con ID: " +  idMora , "WARNING",
            JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION) {
                boolean exito = moraController.pagoMora(idMora,monto,user);
                if (exito) {
                    cargarMora(moraController.obtenerMoraPendiente(user));
                    JOptionPane.showMessageDialog(null, "Pago realizado correctamente.");
                } else {
                    JOptionPane.showMessageDialog(null, "Error al confirmar pago.");
                }
            }
        }else{
            JOptionPane.showMessageDialog(null, "No cuentas con permisos para realizar la acción. Contacta a un adminstrador.");
        }
       
    }//GEN-LAST:event_tbl_mis_morasMouseClicked

