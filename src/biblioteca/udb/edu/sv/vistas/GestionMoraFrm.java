    private void cargarMora(List<Mora> mor){
        modelMora.setRowCount(0); // Limpiar tabla
        mor.forEach(m -> {
            modelMora.addRow(new Object[]{
                m.getMoraID(),
                m.getPrestamo().getEjemplar().getDocumento().getTitulo(),
                m.getUsuario().getCorreo(),
                m.getPrestamo().getFechaPrestamo(),
                m.getPrestamo().getFechaDevolucionPrevista(),
                m.getDiasRetraso(),
                m.getMonto(),
                m.getPagado(),
                m.getObservaciones()
            });
        });
    }

